MAX_FILES = 8
MAX_FILE_BYTES = 18_000
MAX_TOTAL_BYTES = 85_000
MAX_SPEC = 4_000
ALLOWED_SUFFIXES = {'.py', '.js', '.jsx', '.ts', '.tsx', '.dart', '.html', '.css', '.json', '.md', '.yaml', '.yml', '.sql', '.txt'}
BLOCKED_SEGMENTS = {'.git', '.github', '.env', 'node_modules', '__pycache__', 'vendor', 'dist', 'build', 'secrets', '.ssh'}
WORKERS = set()
WORKERS_LOCK = threading.Lock()


def parse_json(raw):
    if not isinstance(raw, str) or len(raw) > 250_000:
        raise ValueError('AI trả dữ liệu không hợp lệ hoặc quá lớn')
    raw = raw.strip()
    if raw.startswith('```'):
        raw = re.sub(r'^```(?:json)?\s*', '', raw, flags=re.I)
        raw = re.sub(r'\s*```$', '', raw)
    try:
        return json.loads(raw)
    except (json.JSONDecodeError, TypeError):
        raise ValueError('AI không trả JSON hợp lệ; không sử dụng mã') from None


def safe_path(value):
    if not isinstance(value, str) or not 1 <= len(value) <= 140:
        raise ValueError('Đường dẫn file không hợp lệ')
    if ('\\' in value or '\x00' in value or ':' in value or value.startswith('/')
            or any(ord(c) < 32 for c in value)):
        raise ValueError('Đường dẫn file có ký tự bị chặn')
    parts = value.split('/')
    if (len(parts) > 7 or any(not p or p in ('.', '..') or p.startswith('.')
                             or p.lower() in BLOCKED_SEGMENTS for p in parts)):
        raise ValueError('Đường dẫn file chứa phân đoạn không an toàn')
    path = PurePosixPath(value)
    if path.suffix.lower() not in ALLOWED_SUFFIXES:
        raise ValueError('Định dạng file chưa được hỗ trợ: ' + path.suffix)
    return value


def validate_proposal(source):
    obj = parse_json(source) if isinstance(source, str) else source
    if not isinstance(obj, dict) or not isinstance(obj.get('files'), list):
        raise ValueError('Proposal phải có trường files[]')
    files = obj['files']
    if not 1 <= len(files) <= MAX_FILES:
        raise ValueError('Chỉ cho phép 1–8 files mỗi phương án')
    result, seen, total = [], set(), 0
    for item in files:
        if not isinstance(item, dict):
            raise ValueError('File không hợp lệ')
        path = safe_path(item.get('path'))
        content = item.get('content')
        if not isinstance(content, str):
            raise ValueError('Nội dung file phải là text')
        count = len(content.encode('utf-8'))
        if count > MAX_FILE_BYTES:
            raise ValueError('File vượt 18 KB: ' + path)
        total += count
        if total > MAX_TOTAL_BYTES or path.casefold() in seen:
            raise ValueError('File bị trùng tên hoặc tổng kích thước vượt 85 KB')
        seen.add(path.casefold())
        result.append({'path': path, 'content': content,
                       'sha256': hashlib.sha256(content.encode('utf-8')).hexdigest()})
    description = str(obj.get('summary', ''))[:1000]
    return {'summary': description, 'files': result, 'total_bytes': total}


def render_proposal(proposal):
    """Limited, untrusted code context for reviewing, not an execution request."""
    return '\n\n'.join(f"FILE: {f['path']}\n```\n{f['content']}\n```" for f in proposal['files'])[:90_000]


